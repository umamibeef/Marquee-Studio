// Export the decompile of every function, plus a header that makes it checkable as C:
//   <out>.c              the decompiled functions
//   <out>.functions.txt  address, name, size
//   <out>.h              data types, a prototype per function and an extern per global the decompiler used,
//                        each with the type the decompiler gave it (tools/compile_check.py compiles against it)
import ghidra.app.script.GhidraScript;
import ghidra.app.decompiler.*;
import ghidra.program.model.data.*;
import ghidra.program.model.listing.*;
import ghidra.program.model.pcode.*;
import java.io.*;
import java.util.*;

public class ExportDecomp extends GhidraScript {
    public void run() throws Exception {
        String out = getScriptArgs().length > 0 ? getScriptArgs()[0] : "/tmp/decomp";
        DecompInterface di = new DecompInterface();
        di.openProgram(currentProgram);
        PrintWriter cw = new PrintWriter(new FileWriter(out + ".c"));
        PrintWriter lw = new PrintWriter(new FileWriter(out + ".functions.txt"));
        PrintWriter gw = new PrintWriter(new FileWriter(out + ".globals.tsv"));   // per function: name, declaration
        PrintWriter aw = new PrintWriter(new FileWriter(out + ".access.tsv"));    // per function: address, access size
        Map<String, String> protos = new LinkedHashMap<>();
        Map<String, String> globals = new TreeMap<>();
        Map<String, Set<String>> clashes = new TreeMap<>();
        FunctionIterator fns = currentProgram.getFunctionManager().getFunctions(true);
        int n = 0, ok = 0;
        while (fns.hasNext() && !monitor.isCancelled()) {
            Function f = fns.next();
            n++;
            lw.println(f.getEntryPoint() + "  " + f.getName() + "  (" + f.getBody().getNumAddresses() + " bytes)");
            cw.println("/* === " + f.getEntryPoint() + "  " + f.getName() + " === */");
            DecompileResults r = di.decompileFunction(f, 90, monitor);
            if (r != null && r.decompileCompleted()) {
                DecompiledFunction d = r.getDecompiledFunction();
                cw.println(d.getC());
                protos.putIfAbsent(f.getName(), d.getSignature().trim());
                HighFunction hf = r.getHighFunction();
                if (hf != null) {
                    Iterator<HighSymbol> it = hf.getGlobalSymbolMap().getSymbols();
                    while (it.hasNext()) {
                        HighSymbol s = it.next();
                        if (s.getDataType() == null) continue;
                        String nm = s.getName().replaceAll("[^A-Za-z0-9_]", "_");   // as the decompiler prints it
                        String decl = declare(s.getDataType(), nm);
                        gw.println(f.getName() + "\t" + nm + "\t" + decl + "\t" + s.getSize());
                        String prev = globals.putIfAbsent(nm, decl);
                        if (prev != null && !prev.equals(decl))
                            clashes.computeIfAbsent(nm, k -> new TreeSet<>(List.of(prev))).add(decl);
                    }
                }
                // access widths of fixed memory addresses in this function (p-code varnodes in RAM space)
                if (hf != null) {
                    Map<Long, Set<Integer>> acc = new TreeMap<>();
                    Iterator<PcodeOpAST> ops = hf.getPcodeOps();
                    while (ops.hasNext()) {
                        PcodeOpAST op = ops.next();
                        List<Varnode> vs = new ArrayList<>(Arrays.asList(op.getInputs()));
                        if (op.getOutput() != null) vs.add(op.getOutput());
                        for (Varnode v : vs)
                            if (v != null && v.isAddress() && v.getAddress().isMemoryAddress())
                                acc.computeIfAbsent(v.getAddress().getOffset(), k -> new TreeSet<>()).add(v.getSize());
                    }
                    for (Map.Entry<Long, Set<Integer>> e : acc.entrySet())
                        for (int sz : e.getValue())
                            aw.println(f.getName() + "\t" + String.format("%08x", e.getKey()) + "\t" + sz);
                }
                ok++;
            } else cw.println("// decompile failed: " + (r == null ? "null" : r.getErrorMessage()));
            cw.println();
            if (n % 200 == 0) { cw.flush(); println("  " + n); }
        }
        cw.close(); lw.close(); gw.close(); aw.close();

        PrintWriter hw = new PrintWriter(new FileWriter(out + ".h"));
        hw.println("/* Generated by gscripts/ExportDecomp.java: types, prototypes and globals for " + out + ".c */");
        hw.println("/* ---- data types ---- */");
        StringWriter types = new StringWriter();
        List<DataType> all = new ArrayList<>();
        currentProgram.getDataTypeManager().getAllDataTypes(all);
        new DataTypeWriter(currentProgram.getDataTypeManager(), types).write(all, monitor);
        hw.println(types);
        hw.println("/* ---- functions ---- */");
        for (String p : protos.values()) hw.println(p.endsWith(";") ? p : p + ";");
        hw.println("/* ---- globals (" + clashes.size() + " used with more than one type; first kept) ---- */");
        for (Map.Entry<String, String> g : globals.entrySet()) {
            if (protos.containsKey(g.getKey())) continue;          // a function used as data
            hw.println("extern " + g.getValue() + ";" + (clashes.containsKey(g.getKey())
                    ? "  /* also: " + String.join(" | ", clashes.get(g.getKey())) + " */" : ""));
        }
        hw.close();
        println("DONE decompiled " + ok + "/" + n + " -> " + out + ".c (+ .h: " + protos.size()
                + " prototypes, " + globals.size() + " globals)");
    }

    /** C declaration of `name` with type t: arrays and pointers to arrays spelled out. */
    private String declare(DataType t, String name) {
        if (t instanceof TypeDef && ((TypeDef) t).getBaseDataType() instanceof Array)
            return t.getDisplayName().replaceAll("[^A-Za-z0-9_ *]", "_") + " " + name;
        if (t instanceof Array) {
            Array a = (Array) t;
            return declare(a.getDataType(), name + "[" + a.getNumElements() + "]");
        }
        if (t instanceof Pointer && ((Pointer) t).getDataType() instanceof FunctionDefinition) {
            FunctionDefinition fd = (FunctionDefinition) ((Pointer) t).getDataType();
            return fd.getReturnType().getDisplayName() + " (*" + name + ")()";
        }
        if (t instanceof FunctionDefinition) return ((FunctionDefinition) t).getReturnType().getDisplayName() + " " + name + "()";
        return t.getDisplayName().replaceAll("[^A-Za-z0-9_ *]", "_") + " " + name;
    }
}
