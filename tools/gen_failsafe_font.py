#!/usr/bin/env python3
"""The failsafe's glyphs, from a vendored BDF font: only the characters its messages use.
Usage: gen_failsafe_font.py FONT.bdf OUT.h"""
import sys

CHARS = " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-:.,"


def glyphs(path):
    out, enc, rows = {}, None, None
    for line in open(path, encoding="latin-1"):
        w = line.split()
        if not w:
            continue
        if w[0] == "ENCODING":
            enc = int(w[1])
        elif w[0] == "BITMAP":
            rows = []
        elif w[0] == "ENDCHAR":
            out[enc], rows = rows, None
        elif rows is not None:
            rows.append(int(w[0], 16))
    return out


def main():
    g = glyphs(sys.argv[1])
    with open(sys.argv[2], "w") as f:
        f.write("/* Generated by tools/gen_failsafe_font.py from %s. */\n" % sys.argv[1].split("/")[-1])
        f.write('static const char font_chars[] = "%s";\n' % CHARS)
        f.write("static const unsigned char font_rows[%d][16] = {\n" % len(CHARS))
        for c in CHARS:
            rows = g[ord(c)]
            assert len(rows) == 16, c
            f.write("\t{%s},\n" % ",".join("0x%02X" % r for r in rows))
        f.write("};\n")


main()
